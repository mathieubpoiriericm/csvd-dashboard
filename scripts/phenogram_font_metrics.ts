/**
 * Writes `lib/phenogram_font_metrics.json`: the advance width of every code
 * point the phenogram's two Barlow faces draw, read from the shipped WOFF2
 * files. Both phenogram renderers size each chromosome's label column from
 * this table, so the layout never depends on a browser's or matplotlib's
 * text measurement -- and Python, which has no Brotli, only reads the JSON.
 *
 * Run `deno task phenogram:metrics` after changing either font file;
 * `tests/phenogram_font_metrics_test.ts` fails until the table matches them.
 */
import { woff2Metrics } from "../tests/helpers/woff2.ts";

/** The weights the karyogram sets text in: pills at 400, symbols at 600. */
export const WEIGHTS = [400, 600] as const;

export const METRICS_PATH = new URL(
  "../lib/phenogram_font_metrics.json",
  import.meta.url,
);

export interface FontMetricsTable {
  $comment: string;
  unitsPerEm: number;
  /** Weight to code point (decimal) to advance, in font units. */
  advances: Record<string, Record<string, number>>;
}

/** The table the shipped fonts give. */
export function fontMetricsTable(): FontMetricsTable {
  let unitsPerEm: number | null = null;
  const advances: Record<string, Record<string, number>> = {};
  for (const weight of WEIGHTS) {
    const file = new URL(
      `../assets/fonts/Barlow-${weight}-latin.woff2`,
      import.meta.url,
    );
    const metrics = woff2Metrics(Deno.readFileSync(file));
    if (unitsPerEm !== null && metrics.unitsPerEm !== unitsPerEm) {
      throw new Error(
        `Barlow ${weight} has ${metrics.unitsPerEm} units per em, not ${unitsPerEm}`,
      );
    }
    unitsPerEm = metrics.unitsPerEm;
    advances[String(weight)] = Object.fromEntries(
      [...metrics.advances].sort(([a], [b]) => a - b)
        .map(([code, advance]) => [String(code), advance]),
    );
  }
  return {
    $comment:
      "Generated by `deno task phenogram:metrics` from assets/fonts/Barlow-{400,600}-latin.woff2; do not edit. Advance widths in font units, by weight and decimal code point.",
    unitsPerEm: unitsPerEm!,
    advances,
  };
}

if (import.meta.main) {
  Deno.writeTextFileSync(
    METRICS_PATH,
    JSON.stringify(fontMetricsTable(), null, 2) + "\n",
  );
  const fmt = new Deno.Command(Deno.execPath(), {
    args: ["fmt", METRICS_PATH.pathname],
  }).outputSync();
  if (!fmt.success) throw new Error(new TextDecoder().decode(fmt.stderr));
  console.log(`Wrote ${METRICS_PATH.pathname}`);
}
